-- Neon Postgres schema for coin prices, predictions and positions.
-- Safe to run repeatedly. seed_neon_from_local.py applies this before loading data.

CREATE TABLE IF NOT EXISTS coin_prices (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coin_id TEXT NOT NULL,
    coin_name TEXT,
    date DATE NOT NULL,
    price DOUBLE PRECISION,
    ma7 DOUBLE PRECISION,
    ma14 DOUBLE PRECISION,
    ma30 DOUBLE PRECISION,
    ema7 DOUBLE PRECISION,
    ema14 DOUBLE PRECISION,
    daily_return DOUBLE PRECISION,
    volatility7 DOUBLE PRECISION,
    volatility14 DOUBLE PRECISION,
    rsi14 DOUBLE PRECISION,
    macd DOUBLE PRECISION,
    macd_signal DOUBLE PRECISION,
    macd_hist DOUBLE PRECISION,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_coin_prices UNIQUE (coin_id, date)
);

CREATE TABLE IF NOT EXISTS coin_predictions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coin_id TEXT NOT NULL,
    prediction_date DATE NOT NULL,
    target_date DATE NOT NULL,
    predicted_price DOUBLE PRECISION NOT NULL,
    actual_price DOUBLE PRECISION,
    model_name TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS positions (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coin_id TEXT,
    open_date TEXT,
    close_date TEXT,
    predicted_open_price DOUBLE PRECISION,
    predicted_close_price DOUBLE PRECISION,
    actual_open_price DOUBLE PRECISION,
    actual_close_price DOUBLE PRECISION,
    position_type TEXT,
    profit_loss DOUBLE PRECISION,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_coin_predictions_coin_id ON coin_predictions (coin_id);
CREATE INDEX IF NOT EXISTS ix_coin_predictions_prediction_date ON coin_predictions (prediction_date);
CREATE INDEX IF NOT EXISTS ix_positions_coin_id ON positions (coin_id);
